//! Rust source for module registration and standalone executables built by `zkcl build`.

use std::fmt::Write as _;

use crate::{AotRegistrationEntry, fasl_symbol_name};

/// Generate Rust declarations for the AOT object symbols and descriptors for runtime registration.
/// Compile the returned source with the same object that supplied `registration_entries`
/// and `fasl_bytes`.
pub fn generate_registration_source(
    module_id: &str,
    registration_entries: &[AotRegistrationEntry],
    fasl_bytes: &[u8],
) -> String {
    let mut out = String::with_capacity(4096);
    let fasl_symbol = fasl_symbol_name(module_id);
    let fasl_len = fasl_bytes.len();
    let escaped_module_id = module_id.escape_default();

    let _ = writeln!(
        out,
        "// @generated by zkcl-aot for module `{escaped_module_id}`."
    );
    out.push_str(
        r#"#![allow(dead_code, unused_imports)]

use zkcl::native::{
    AbiFingerprint, AotCodeDescriptor, AotModuleDescriptor, Arity, JitCEntryFn,
    FixnumArithmetic, FixnumComparison, IntegerBitPrimitive, JitCallContext, JitReturn,
    LeafGuard, LeafPrimitive, jit_c_trampoline,
};
use zkcl::{EvalError, Runtime};

#[allow(improper_ctypes, reason = "JitCallContext is passed as an opaque runtime-owned pointer")]
unsafe extern "C" {
"#,
    );
    let _ = writeln!(out, "    static {fasl_symbol}: [u8; {fasl_len}];");
    for function in registration_entries {
        let _ = writeln!(
            out,
            "    fn {}(ctx: *mut JitCallContext, target: usize, args_ptr: *const usize, argc: usize, out_ret: *mut JitReturn);",
            function.symbol_name
        );
        if let Some(leaf) = &function.leaf_symbol {
            let _ = writeln!(
                out,
                "    fn {leaf}(a: usize, b: usize, c: usize, d: usize) -> usize;"
            );
        }
    }
    let _ = write!(
        out,
        "}}\n\n\
/// Embedded FASL payload slice from the AOT object file's read-only data section.\n\
pub static FASL_BYTES: &[u8] = unsafe {{ &{fasl_symbol} }};\n\n\
        ",
    );
    out.push_str(
        r#"/// Raw C-ABI AOT entry points indexed by `entry_index`.
pub const AOT_C_ENTRIES: &[(u32, JitCEntryFn)] = &[
"#,
    );
    for function in registration_entries {
        let _ = writeln!(
            out,
            "    ({}, {}),",
            function.entry_index, function.symbol_name
        );
    }

    out.push_str("];\n\npub static AOT_CODES: &[AotCodeDescriptor] = &[\n");
    for function in registration_entries {
        let maximum_arity = match function.arity.maximum {
            Some(maximum) => format!("Some({maximum})"),
            None => "None".to_string(),
        };
        let leaf_entry = function
            .leaf_symbol
            .as_ref()
            .map_or("None".into(), |symbol| format!("Some({symbol})"));
        let mut guards = String::new();
        for &zkcl_bytecode::native_abi::LeafGuard { symbol, primitive } in &function.leaf_guards {
            use zkcl_bytecode::native_abi::LeafPrimitive;
            match primitive {
                LeafPrimitive::Arithmetic(op) => {
                    let _ = write!(
                        guards,
                        "LeafGuard {{ symbol: {symbol}, primitive: LeafPrimitive::Arithmetic(FixnumArithmetic::{op:?}) }}, "
                    );
                }
                LeafPrimitive::Compare(relation) => {
                    let _ = write!(
                        guards,
                        "LeafGuard {{ symbol: {symbol}, primitive: LeafPrimitive::Compare(FixnumComparison::{relation:?}) }}, "
                    );
                }
                LeafPrimitive::IntegerBits(op) => {
                    let _ = write!(
                        guards,
                        "LeafGuard {{ symbol: {symbol}, primitive: LeafPrimitive::IntegerBits(IntegerBitPrimitive::{op:?}) }}, "
                    );
                }
            }
        }
        let _ = writeln!(
            out,
            r#"    AotCodeDescriptor {{
        native_debug: {},
        entry_index: {},
        arity: Arity {{ required: {}, maximum: {maximum_arity} }},
        root_slots: {},
        fast_entry: None,
        generic_entry: jit_c_trampoline,
        c_entry: Some({}),
        continuation_abi: Some({}),
        leaf_entry: {leaf_entry},
        leaf_guards: &[{guards}],
    }},"#,
            function.native_debug,
            function.entry_index,
            function.arity.required,
            function.root_slots,
            function.symbol_name,
            zkcl_bytecode::native_abi::NATIVE_CALL_ABI_REVISION,
        );
    }
    let _ = write!(
        out,
        r#"];

// SAFETY: The linked object supplies the native entries and the exact FASL they implement.
pub static AOT_MODULE: AotModuleDescriptor = unsafe {{
    AotModuleDescriptor::new("{escaped_module_id}", AbiFingerprint::CURRENT, Some(FASL_BYTES), AOT_CODES)
}};

"#,
    );
    out.push_str(
        r#"/// Register this AOT module on `runtime` without executing top-level FASL forms.
pub fn register(runtime: &Runtime) -> Result<(), EvalError> {
    runtime.register_aot_module(&AOT_MODULE)
}

/// Register this AOT module and load its embedded FASL payload on `runtime`.
pub fn load(runtime: &Runtime) -> Result<(), EvalError> {
    runtime.load_aot_module(&AOT_MODULE)
}
"#,
    );

    out
}

/// Generate a standalone `main.rs` template for `zkcl build` executables.
pub fn generate_standalone_main_source(module_id: &str, fasl_include_path: Option<&str>) -> String {
    let mut out = String::with_capacity(1024);

    let escaped_module_id = module_id.escape_default();
    let _ = writeln!(
        out,
        "// Standalone executable entry point generated by zkcl-aot for module `{escaped_module_id}`."
    );
    out.push_str("mod aot_module;\n\n");

    if let Some(path) = fasl_include_path {
        let escaped_path = path.escape_default();
        let _ = writeln!(
            out,
            "static EMBEDDED_FASL_OVERRIDE: &[u8] = include_bytes!(\"{escaped_path}\");\n"
        );
    }

    out.push_str(
        r#"fn main() -> Result<std::process::ExitCode, Box<dyn std::error::Error>> {
    #[cfg(feature = "ffi")]
    let runtime = unsafe { zkcl::Runtime::builder().allow_foreign_calls() }.start()?;
    #[cfg(not(feature = "ffi"))]
    let runtime = zkcl::Runtime::start()?;
    let arguments = std::env::args_os().skip(1).map(|arg| arg.into_string().map_err(|_| std::io::Error::new(std::io::ErrorKind::InvalidData, "script arguments must be UTF-8"))).collect::<Result<Vec<_>, _>>()?;
    runtime.set_command_line_arguments(arguments);
"#,
    );
    if fasl_include_path.is_some() {
        out.push_str(
            r#"    if EMBEDDED_FASL_OVERRIDE == aot_module::FASL_BYTES {
        runtime.load_aot_module(&aot_module::AOT_MODULE)?;
    } else {
        runtime.load_fasl(EMBEDDED_FASL_OVERRIDE)?;
    }
"#,
        );
    } else {
        out.push_str("    runtime.load_aot_module(&aot_module::AOT_MODULE)?;\n");
    }
    out.push_str(
        r#"    Ok(std::process::ExitCode::from(runtime.requested_exit_code()))
}
"#,
    );

    out
}
