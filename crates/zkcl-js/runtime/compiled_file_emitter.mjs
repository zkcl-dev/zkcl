const arrayElements = {
  general: 'General', character: 'Character', bit: 'Bit', octet: 'Octet', single: 'SingleFloat', double: 'DoubleFloat',
};
export const compiledModuleHeader = '// Generated by zkcl-js.';

function loadFormOrder(actions) {
  const ordered = [], emitted = new Set(), visiting = new Set();
  for (const action of actions) {
    if (emitted.has(action)) continue;
    const stack = [{ action, dependencies: action.requires.values() }];
    visiting.add(action);
    while (stack.length) {
      const current = stack.at(-1), next = current.dependencies.next();
      if (next.done) {
        stack.pop();
        visiting.delete(current.action);
        emitted.add(current.action);
        ordered.push(current.action);
      } else if (!emitted.has(next.value)) {
        if (visiting.has(next.value)) return null;
        visiting.add(next.value);
        stack.push({ action: next.value, dependencies: next.value.requires.values() });
      }
    }
  }
  return ordered;
}

function loadFormDependsOn(action, dependency) {
  const pending = [action], seen = new Set();
  for (const step of pending) {
    if (step === dependency) return true;
    if (seen.has(step)) continue;
    seen.add(step);
    for (const prerequisite of step.requires) pending.push(prerequisite);
  }
  return false;
}

// Both kinds of forms require the creation of every object they reference.
// Prefer to initialize those objects first wherever initialization is acyclic.
function scheduleLoadForms(forms, firstNode, references) {
  const actions = [], prefer = [];
  for (const [node, { create, initialize }] of forms) {
    actions.push(create);
    if (initialize) {
      initialize.requires.add(create);
      actions.push(initialize);
    }
    for (const action of initialize ? [create, initialize] : [create]) {
      const pending = [...action.entry.constants], seen = new Set();
      for (const index of pending) {
        if (index < firstNode || seen.has(index)) continue;
        seen.add(index);
        const other = forms.get(index);
        if (other) {
          action.requires.add(other.create);
          if (index !== node && other.initialize) prefer.push([action, other.initialize]);
        } else {
          for (const ref of references[index]) pending.push(ref);
        }
      }
    }
  }
  for (const [action, dependency] of prefer) action.requires.add(dependency);
  const ordered = loadFormOrder(actions);
  if (ordered) return ordered;
  for (const [action, dependency] of prefer) action.requires.delete(dependency);
  if (!loadFormOrder(actions)) {
    throw new LispCondition('PROGRAM-ERROR', 'Circular dependency between MAKE-LOAD-FORM creation forms');
  }
  for (const [action, dependency] of prefer) {
    if (!loadFormDependsOn(dependency, action)) action.requires.add(dependency);
  }
  return loadFormOrder(actions);
}

/** Emit the same portable program graph consumed by loadProgram and exported
 * by the Rust emitter. Finish each top-level literal graph while its compile
 * environment is active, so user-defined load forms run before the next read.
 */
export function createResidentEmitter(runtime, sourcePath, compileForm) {
  const nodes = [], indices = new Map(), pending = [], references = [], entries = [];
  const ref = value => {
    if (!indices.has(value)) { indices.set(value, pending.length); pending.push(value); }
    return indices.get(value);
  };
  const record = (code, constants = code.constants) => ({ code, constants: constants.map(ref) });
  const loadForm = runtime.intern('MAKE-LOAD-FORM', 'COMMON-LISP');
  const codeSource = ({ code, constants }, kind, index, steps) => {
    const { name, source_file, arity, registers, captures, constants: _constants,
      debug, instructions, step, operands, source_pcs, instruction_count, ...other } = code;
    const label = `${stepIdentifier(name)}_0_${kind}${index}`, comments = [];
    const generated = generateStep(code, (slot, pc, operation, symbol) => {
      comments[slot] = `Operand ${slot}, PC ${pc}: ${operation}${symbol ? ` ${symbol}` : ''}`;
    });
    steps.push(`function ${label}(task, frame) {\n${generated.source}\n}`);
    const fields = { name, source_file, arity, registers, captures, constants,
      ...other, debug, instruction_count: generated.instruction_count, source_pcs: generated.source_pcs };
    const fieldIndent = jsIndent(3), operandIndent = jsIndent(4);
    let output = '{\n';
    for (const [field, value] of Object.entries(fields)) {
      if (value !== undefined) output += `${fieldIndent}${field}: ${jsValue(value, 3)},\n`;
    }
    output += `${fieldIndent}operands: [`;
    if (generated.operands.length) {
      output += '\n';
      generated.operands.forEach((operand, i) => {
        output += `${operandIndent}// ${comments[i]}\n${operandIndent}${jsValue(operand, 4)},\n`;
      });
      output += fieldIndent;
    }
    return `${output}],\n${fieldIndent}step: ${label},\n${jsIndent(2)}}`;
  };
  const unsupported = value => { throw new LispCondition('PROGRAM-ERROR', `Cannot store ${value?.constructor?.name ?? typeof value} in a JavaScript compiled file`, { datum: value }); };

  function encode(value, ref, loadTimeCells) {
    if (value === NIL) return 'Nil';
    if (value === T) return 'True';
    if (value === UNBOUND) return 'Unbound';
    if (Number.isInteger(value) || typeof value === 'bigint') {
      if (typeof value === 'number' && value >= -268435456 && value <= 268435455) return { Fixnum: String(value) };
      if (typeof value === 'number' && !Number.isSafeInteger(value)) return unsupported(value);
      const n = BigInt(value), magnitude = [];
      for (let remaining = n < 0n ? -n : n; remaining > 0n; remaining >>= 8n) magnitude.push(Number(remaining & 255n));
      return { Bignum: { negative: n < 0n, magnitude } };
    }
    if (value instanceof LispCharacter) return { Character: value.toString() };
    if (value instanceof LispString) return { String: value.toString() };
    if (value instanceof LispSymbol) return value.package ? { InternedSymbol: { package: value.package.name, name: value.name } } : { UninternedSymbol: value.name };
    if (typeof value?.name === 'string' && runtime.packages.get(value.name) === value) return { Package: value.name };
    if (value instanceof Cons) return { Pair: [ref(value.car), ref(value.cdr)] };
    if (value instanceof Cell) return { LexicalCell: ref(loadTimeCells.has(value) ? UNBOUND : value.value) };
    if (value instanceof Closure) return { Closure: { code: ref(value.code), captures: value.environment.map(ref), documentation: ref(value.documentation ?? NIL) } };
    if (value instanceof LispPathname) return { Pathname: value.components.map(ref) };
    if (value instanceof SingleFloat) return { SingleFloat: value.bits };
    if (value instanceof DoubleFloat) return { DoubleFloat: String(value.bits) };
    if (value instanceof RandomState) return { RandomState: value.words.map(String) };
    if (value instanceof Ratio) return { Ratio: [ref(value.numerator), ref(value.denominator)] };
    if (value instanceof Complex) return { Complex: [ref(value.real), ref(value.imaginary)] };
    if (value instanceof LispHashTable) {
      const hint = value => typeof value === 'number' || typeof value === 'bigint'
        ? String(BigInt(value) < 0x8000000000000000n ? value : 0x7fffffffffffffffn)
        : String(0x8000000000000000n | new DoubleFloat(toNumber(value)).bits);
      return { HashTable: { test: { EQ: 'Eq', EQL: 'Eql', EQUAL: 'Equal', EQUALP: 'Equalp' }[value.testName],
        weakness: null, rehash_size: hint(value.rehashSize), rehash_threshold: hint(value.rehashThreshold),
        entries: Array.from(value.entries(), ([k, v]) => [ref(k), ref(v)]) } };
    }
    if (value instanceof LispArray) {
      let contents;
      if (value.displacedTo) contents = { Displaced: { target: ref(value.displacedTo), offset: value.displacedIndexOffset } };
      else if (value.elementKind === 'octet') contents = { Octets: value.storage.map(Number) };
      else if (value.elementKind === 'single') contents = { SingleFloats: value.storage.map(x => x.bits) };
      else if (value.elementKind === 'double') contents = { DoubleFloats: value.storage.map(x => String(x.bits)) };
      else contents = { Elements: value.storage.map(ref) };
      return { Array: { dimensions: value.dimensions, element: arrayElements[value.elementKind], adjustable: value.adjustable, fill_pointer: value.fillPointer, contents } };
    }
    return unsupported(value);
  }

  function* addEntry(code, loadTimeCells, environment) {
    const firstNode = nodes.length, entry = record(code), forms = new Map();
    for (let i = firstNode; i < pending.length; i++) {
      const value = pending[i];
      if (value instanceof LispCode) {
        const description = record(value.entry, value.constants);
        nodes.push({ Function: description });
        references.push(description.constants);
      } else if (runtime.isStandardInstance(value) || value instanceof StructureInstance || value instanceof LispCondition) {
        const [creation = NIL, initialization = NIL] = (yield runtime.requestCall(loadForm, [value, environment])).values;
        const descriptor = { creation: null, initialization: null };
        const create = { descriptor, kind: 'creation', entry: record(yield* compileForm(creation, environment)), requires: new Set() };
        const initialize = initialization === NIL ? null : { descriptor, kind: 'initialization',
          entry: record(yield* compileForm(initialization, environment)), requires: new Set() };
        forms.set(i, { create, initialize });
        nodes.push({ LoadForm: descriptor });
        references.push([]);
      } else {
        const edges = [];
        nodes.push(encode(value, object => {
          const index = ref(object);
          edges.push(index);
          return index;
        }, loadTimeCells));
        references.push(edges);
      }
    }
    for (const action of scheduleLoadForms(forms, firstNode, references)) {
      action.descriptor[action.kind] = entries.length;
      entries.push(action.entry);
    }
    entries.push(entry);
  }

  function finish() {
    const steps = [];
    const entrySources = entries.map((entry, index) => codeSource(entry, 'e', index, steps));
    const nodeSources = nodes.map((node, index) => node.Function
      ? `{ Function: ${codeSource(node.Function, 'n', index, steps)} }` : jsValue(node, 2));
    const sourceFiles = sourcePath ? [{ uri: null, version: null, base_offset: 0, path: sourcePath, text: null }] : [];
    const indexed = items => items.map((item, index) => `    /* ${index} */ ${item},\n`).join('');
    const declarations = steps.length ? `${steps.join('\n\n')}\n\n` : '';
    return `${compiledModuleHeader} This module contains compiled Lisp code.\n\n` +
      `// Compiled Lisp code. Each case is an instruction and a possible resume point.\n${declarations}` +
      `// Program data. Constant indices refer to the literal graph.\nexport const program = {\n` +
      `  target: "js",\n  source_files: ${jsValue(sourceFiles, 1)},\n` +
      `  nodes: [\n${indexed(nodeSources)}  ],\n  entries: [\n${indexed(entrySources)}  ],\n};\n` +
      'export const programs = [program];\n';
  }
  return { addEntry, finish };
}
