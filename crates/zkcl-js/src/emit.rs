const RUNTIME_BUNDLE: &str = include_str!(concat!(env!("OUT_DIR"), "/zkcl-runtime.mjs"));
const COMPILED_MODULE_HEADER: &str = "// Generated by zkcl-js.\n";

// Match the JavaScript runtime's exclusive multiple-value limit. Ranges at or
// above it use the runtime operation to signal the standard condition.
const MULTIPLE_VALUES_LIMIT: usize = 65_536;

// A function's data object sits inside `nodes: [` and the `{ Function: ... }`
// literal wrapper, so its fields start three levels below the program object.
const FUNCTION_FIELD_LEVEL: usize = 3;

// A step body indents the statements of one instruction by six spaces: two for
// the function body, two for the dispatch loop, and two for the `case` block.
// Source-map marks point at the statement after the resume scaffolding, so this
// indent is part of the mapping and not only of the layout.
const STEP_STATEMENT_INDENT: usize = 6;

/// A compiled input cannot be emitted for the JavaScript runtime.
#[derive(Debug, thiserror::Error)]
pub enum EmitError {
    #[error(transparent)]
    CompiledFile(#[from] zkcl_bytecode::CompiledFileError),
    #[error("could not encode JavaScript metadata: {0}")]
    Metadata(#[from] serde_json::Error),
    #[error(
        "compiled-file index or source position {value} exceeds JavaScript's exact integer range"
    )]
    IntegerRange { value: String },
    #[error(
        "expected a package-qualified project entry PACKAGE:NAME or PACKAGE::NAME, found {entry:?}"
    )]
    InvalidEntry { entry: String },
    #[error("JavaScript compiled files cannot contain the native-image literal kind {kind:?}")]
    UnsupportedLiteral { kind: String },
}

/// Emit one independently deployable ES module, including the shared runtime.
///
/// The module exports its programs, runtime constructor, and synchronous and
/// asynchronous entry points. Retained source snapshots and locations produce
/// an inline source map.
/// JavaScript's binary64 JSON numbers cannot preserve all Lisp integers or float
/// bit patterns: signed literals and 64-bit payloads use decimal strings.
pub fn emit_compiled_file(file: &CompiledFile) -> Result<String, EmitError> {
    emit_compiled_files(std::slice::from_ref(file))
}

/// Emit several compiled files as one module, loading them in input order in a
/// shared runtime. `programs` contains all files; `program` names the first file
/// (or `null` for an empty input). Each file retains its own literal graph.
pub fn emit_compiled_files(files: &[CompiledFile]) -> Result<String, EmitError> {
    emit_module(files, None, None)
}

/// Emit code and literals that import a separately delivered zkcl runtime.
/// `runtime` is an ECMAScript module specifier, relative to the output module
/// or resolved by the embedding host. Emit the runtime with the same compiler.
pub fn emit_compiled_files_with_runtime(
    files: &[CompiledFile],
    runtime: &str,
) -> Result<String, EmitError> {
    emit_module(files, None, Some(runtime))
}

/// Emit a project and call its package-qualified entry after loading its files.
/// Package and symbol names use their exact spelling; entry syntax contains one
/// or two colons and nonempty names without whitespace.
pub fn emit_project(files: &[CompiledFile], entry: &str) -> Result<String, EmitError> {
    emit_project_module(files, entry, None)
}

/// Emit a project as a code module that imports a separately delivered runtime.
pub fn emit_project_with_runtime(
    files: &[CompiledFile],
    entry: &str,
    runtime: &str,
) -> Result<String, EmitError> {
    emit_project_module(files, entry, Some(runtime))
}

/// Emit a reusable ES module with the host-facing JavaScript runtime API.
pub fn emit_runtime_module() -> String {
    let exports = "\nexport const { createRuntime, Runtime, Task, MultipleValues, LispCondition, SuspensionError, NIL, T } = __zkcl_modules.runtime;\n";
    let mut output = String::with_capacity(RUNTIME_BUNDLE.len() + exports.len());
    output.push_str(RUNTIME_BUNDLE);
    output.push_str(exports);
    output
}

fn emit_project_module(
    files: &[CompiledFile],
    entry: &str,
    runtime: Option<&str>,
) -> Result<String, EmitError> {
    let invalid = || EmitError::InvalidEntry {
        entry: entry.to_owned(),
    };
    let (package, name) = entry.split_once(':').ok_or_else(invalid)?;
    let name = name.strip_prefix(':').unwrap_or(name);
    if [package, name].iter().any(|part| {
        part.is_empty() || part.contains(|c: char| c == ':' || c.is_whitespace() || c.is_control())
    }) {
        return Err(invalid());
    }
    emit_module(files, Some((package, name)), runtime)
}

fn emit_module(
    files: &[CompiledFile],
    entry: Option<(&str, &str)>,
    runtime: Option<&str>,
) -> Result<String, EmitError> {
    for file in files {
        file.check_target(&CompilationTarget::javascript())?;
        for node in &file.nodes {
            match node {
                LiteralNode::RuntimeObject { kind, .. } => {
                    return Err(EmitError::UnsupportedLiteral { kind: kind.clone() });
                }
                LiteralNode::ExternalResource { .. } => {
                    return Err(EmitError::UnsupportedLiteral {
                        kind: "ExternalResource".into(),
                    });
                }
                _ => {}
            }
        }
        file.validate()
            .map_err(zkcl_bytecode::CompiledFileError::from)?;
    }
    let mut programs = String::from("export const program = ");
    let mut steps = Steps::default();
    // The first file is the module's default program; the rest follow it in the
    // `programs` array that every host entry point loads in order.
    match files.split_first() {
        Some((first, rest)) => {
            emit_program(&mut programs, &mut steps, first, 0, 0)?;
            programs.push_str(";\nexport const programs = [\n  program,\n");
            for (index, file) in rest.iter().enumerate() {
                programs.push_str("  ");
                emit_program(&mut programs, &mut steps, file, index + 1, 1)?;
                programs.push_str(",\n");
            }
            programs.push_str("];\n");
        }
        None => programs.push_str("null;\nexport const programs = [];\n"),
    }

    let entrypoint_length = steps.text.len() + programs.len();
    let mut output = if let Some(runtime) = runtime {
        let mut output = String::with_capacity(entrypoint_length + runtime.len() + 1024);
        output.push_str(COMPILED_MODULE_HEADER);
        write!(
            output,
            "import {{ createRuntime }} from {};\nexport {{ createRuntime }};\n",
            json(&Value::String(runtime.into()))?
        )
        .unwrap();
        output
    } else {
        let mut output = String::with_capacity(entrypoint_length + RUNTIME_BUNDLE.len() + 1024);
        output.push_str(COMPILED_MODULE_HEADER);
        output.push_str(RUNTIME_BUNDLE);
        output.push_str("\nexport const createRuntime = __zkcl_modules.runtime.createRuntime;\n");
        output
    };
    output.push_str(
        "\n// Compiled Lisp code. Each case is an instruction and a possible resume point.\n",
    );
    let steps_start = output.len();
    output.push_str(&steps.text);
    output.push_str(
        "// Program data. Constant indices refer to the literal graph in the same file.\n",
    );
    output.push_str(&programs);
    output.push_str("\nexport function instantiate(options = {}) {\n  const runtime = createRuntime(options);\n  for (const file of programs) runtime.load(file);\n  return runtime;\n}\n");
    output.push_str("\nexport async function instantiateAsync(options = {}, execution = {}) {\n  const runtime = createRuntime(options);\n  for (const file of programs) await runtime.loadAsync(file, execution);\n  return runtime;\n}\n");
    if let Some((package, name)) = entry {
        let name = json(&Value::String(name.into()))?;
        let package = json(&Value::String(package.into()))?;
        writeln!(output, "\nexport function run(options = {{}}) {{\n  const runtime = instantiate(options);\n  return runtime.call(runtime.intern({name}, {package}));\n}}\n\nexport async function runAsync(options = {{}}, execution = {{}}) {{\n  const runtime = await instantiateAsync(options, execution);\n  return runtime.callAsync(runtime.intern({name}, {package}), [], execution);\n}}").unwrap();
    } else {
        output.push_str(
            "\nexport function run(options = {}) {\n  return instantiate(options).run();\n}\n\nexport async function runAsync(options = {}, execution = {}) {\n  return (await instantiateAsync(options, execution)).run();\n}\n",
        );
    }
    steps.map.append_inline(&mut output, steps_start)?;
    Ok(output)
}

#[derive(Default)]
pub(super) struct Steps<'a> {
    pub(super) text: String,
    pub(super) map: SourceMap<'a>,
}

/// Write one compiled file's program object, starting `depth` levels in.
fn emit_program<'a>(
    output: &mut String,
    steps: &mut Steps<'a>,
    file: &'a CompiledFile,
    file_index: usize,
    depth: usize,
) -> Result<(), EmitError> {
    let indent = indent_str(depth);
    let mut sources = serde_json::to_value(&file.source_files)?;
    // Source revisions are signed 64-bit values too.
    for source in sources.as_array_mut().expect("source files") {
        if !source["version"].is_null() {
            decimal(&mut source["version"]);
        }
    }
    let target = json(&Value::String(file.target.to_string()))?;
    writeln!(output, "{{\n{indent}  target: {target},").unwrap();
    write!(output, "{indent}  source_files: ").unwrap();
    write_value(output, &sources, depth + 1)?;
    output.push_str(",\n");
    write!(output, "{indent}  nodes: [").unwrap();
    if !file.nodes.is_empty() {
        output.push('\n');
    }
    for (index, node) in file.nodes.iter().enumerate() {
        write!(output, "{indent}    /* {index} */ ").unwrap();
        match node {
            LiteralNode::Function(code) => {
                output.push_str("{ Function: ");
                let name = step_name(code.name.as_deref(), file_index, 'n', index);
                emit_function(output, steps, code, &name, depth, file)?;
                output.push_str(" }");
            }
            _ => write_value(output, &literal(node)?, depth + 2)?,
        }
        output.push_str(",\n");
    }
    if !file.nodes.is_empty() {
        write!(output, "{indent}  ").unwrap();
    }
    write!(output, "],\n{indent}  entries: [").unwrap();
    if !file.entries.is_empty() {
        output.push('\n');
    }
    for (index, code) in file.entries.iter().enumerate() {
        let name = step_name(code.name.as_deref(), file_index, 'e', index);
        write!(output, "{indent}    /* {index} */ ").unwrap();
        emit_function(output, steps, code, &name, depth, file)?;
        output.push_str(",\n");
    }
    if !file.entries.is_empty() {
        write!(output, "{indent}  ").unwrap();
    }
    write!(output, "],\n{indent}}}").unwrap();
    Ok(())
}

fn step_name(name: Option<&str>, file: usize, kind: char, index: usize) -> String {
    let label = identifier_fragment(name.unwrap_or("lambda"), 64);
    format!("step_{label}_{file}_{kind}{index}")
}

pub(super) fn identifier_fragment(name: &str, limit: usize) -> String {
    name.chars()
        .take(limit)
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect()
}

fn emit_function<'a>(
    output: &mut String,
    compiled: &mut Steps<'a>,
    code: &'a BytecodeFunction,
    name: &str,
    depth: usize,
    file: &'a CompiledFile,
) -> Result<(), EmitError> {
    let indent = indent_str(depth);
    let field_depth = depth + FUNCTION_FIELD_LEVEL;
    let field_indent = indent_str(field_depth);
    output.push_str("{\n");
    write_function_metadata(output, code, &field_indent, field_depth)?;
    write!(
        output,
        "{field_indent}instruction_count: {},\n{field_indent}source_pcs: ",
        code.instructions.len()
    )
    .unwrap();
    let source_pcs = Value::Array(
        code.instructions
            .iter()
            .map(|instruction| instruction.source_offset().map_or(Value::Null, Value::from))
            .collect(),
    );
    write_value(output, &source_pcs, field_depth)?;
    let mut objects = BTreeSet::new();
    let label_of = |index: usize| constant_label(code, &file.nodes, index);
    let inline: Vec<_> = code
        .instructions
        .iter()
        .map(|instruction| inline_operation(instruction, &mut objects, &label_of))
        .collect();
    let operand_indent = indent_str(field_depth + 1);
    let mut operand_indices = vec![None; code.instructions.len()];
    let mut helpers = Vec::with_capacity(code.instructions.len());
    let mut operand_count = 0;
    write!(output, ",\n{field_indent}operands: [").unwrap();
    for (pc, instruction) in code.instructions.iter().enumerate() {
        if inline[pc].is_some() {
            // Index operands of these operations have no corresponding table
            // bound in the verifier and still need to fit a JavaScript number.
            if let Instruction::ReadValue(_, index) | Instruction::OptionalArgument(index, _) =
                instruction
            {
                check_exact_unsigned(*index as u64)?;
            }
            helpers.push(None);
            continue;
        }
        let (operation_name, payload) = operation(instruction)?;
        let label = instruction_label(instruction, code, &file.nodes);
        if payload.is_null() {
            helpers.push(Some((operation_name, label)));
            continue;
        }
        if operand_count == 0 {
            output.push('\n');
        }
        write!(
            output,
            "{operand_indent}// Operand {operand_count}, PC {pc}: {operation_name}",
        )
        .unwrap();
        if let Some(label) = &label {
            write!(output, " {label}").unwrap();
        }
        output.push('\n');
        output.push_str(&operand_indent);
        write_value(output, &payload, field_depth + 1)?;
        output.push_str(",\n");
        operand_indices[pc] = Some(operand_count);
        operand_count += 1;
        helpers.push(Some((operation_name, label)));
    }
    if operand_count != 0 {
        output.push_str(&field_indent);
    }
    let fast_name = format!("fast_{}", name.strip_prefix("step_").unwrap_or(name));
    let register_names = register_variable_names(code, &file.nodes);
    let source = code
        .source_file
        .map(|index| &file.source_files[index as usize]);
    let fast = crate::structured::try_emit_fast_function(
        compiled,
        code,
        &fast_name,
        &file.nodes,
        &operand_indices,
        &register_names,
        source,
    );
    match &fast {
        Some(emission) => {
            write!(output, "],\n{field_indent}fast: {fast_name},").unwrap();
            if emission.checks_budget {
                write!(output, "\n{field_indent}fastChecksBudget: true,").unwrap();
            }
        }
        None => output.push_str("],"),
    }
    write!(output, "\n{field_indent}step: {name}\n{indent}    }}").unwrap();

    let steps = &mut compiled.text;
    if let Some(at) = code.debug.entry {
        compiled.map.mark(
            steps.len() + "function ".len(),
            source,
            &code.debug,
            at,
            code.name.as_deref(),
        );
    }
    writeln!(steps, "function {name}(task, frame) {{").unwrap();
    steps.push_str(&register_comment(&register_names));
    if operand_count != 0 {
        steps.push_str("  const operands = frame.code.operands;\n");
    }
    if code
        .instructions
        .iter()
        .zip(&inline)
        .any(|(instruction, operation)| {
            operation.is_some()
                && !matches!(
                    instruction,
                    Instruction::Jump(_) | Instruction::ReleaseArguments
                )
        })
    {
        steps.push_str("  const r = frame.registers;\n");
    }
    if !objects.is_empty() {
        let names: Vec<_> = objects.into_iter().collect();
        writeln!(
            steps,
            "  const {{ {} }} = task.runtime.objects;",
            names.join(", ")
        )
        .unwrap();
    }
    steps.push_str("  dispatch: while (true) {\n    switch (frame.pc) {\n");
    for (pc, instruction) in code.instructions.iter().enumerate() {
        let may_transfer = may_transfer_from_helper(instruction);
        let scoped = may_transfer
            || matches!(
                instruction,
                Instruction::UnlessFixnum(..) | Instruction::UnlessFixnumInRange(..)
            );
        writeln!(steps, "    case {pc}:{}", if scoped { " {" } else { "" }).unwrap();
        steps.push_str(
            "      if (task.budget-- <= 0) break dispatch;\n      frame.sourcePc = frame.pc++;\n",
        );
        if may_transfer {
            steps.push_str("      const resumeEpoch = frame.resumeEpoch;\n");
        }
        if let Some(at) = instruction.source_offset() {
            compiled.map.mark(
                steps.len() + STEP_STATEMENT_INDENT,
                source,
                &code.debug,
                at,
                None,
            );
        }
        if let Some(operation) = &inline[pc] {
            operation.emit(steps, pc + 1);
        } else {
            let (helper, label) = helpers[pc].as_ref().expect("runtime helper");
            emit_helper(
                steps,
                instruction,
                helper,
                operand_indices[pc],
                pc + 1,
                label.as_deref(),
                may_transfer,
            );
        }
        if scoped {
            steps.push_str("    }\n");
        }
    }
    writeln!(
        steps,
        "    case {}:\n      return task.returnFrame(frame);",
        code.instructions.len()
    )
    .unwrap();
    steps.push_str("    default:\n      throw new Error('invalid generated function PC: ' + frame.pc);\n    }\n  }\n  task.yielded = true;\n}\n\n");
    Ok(())
}

fn may_transfer_from_helper(instruction: &Instruction) -> bool {
    matches!(
        instruction,
        Instruction::Call { .. }
            | Instruction::CallValues { .. }
            | Instruction::EndCleanup
            | Instruction::ReturnFrom { .. }
            | Instruction::Throw { .. }
            | Instruction::Go { .. }
    )
}

fn emit_helper(
    steps: &mut String,
    instruction: &Instruction,
    name: &str,
    operand_index: Option<usize>,
    next: usize,
    label: Option<&str>,
    may_transfer: bool,
) {
    write!(steps, "      task.ops.{name}(task, frame").unwrap();
    if let Some(index) = operand_index {
        write!(steps, ", operands[{index}]").unwrap();
    }
    steps.push_str(");");
    if let Some(label) = label {
        write!(steps, " // {label}").unwrap();
    }
    steps.push('\n');
    // A thrown error already leaves the step. Only helpers that invoke Lisp or
    // unwind scopes can return with another frame, suspension or completion.
    if may_transfer {
        steps.push_str(
            "      if (task.currentFrame !== frame || task.suspended || task.done || frame.resumeEpoch !== resumeEpoch) return;\n",
        );
    }
    if may_transfer
        || matches!(
            instruction,
            Instruction::BeginCleanup | Instruction::WhenBound { .. }
        )
    {
        writeln!(steps, "      if (frame.pc !== {next}) continue dispatch;").unwrap();
    }
}

pub(super) fn write_symbol_component(out: &mut String, text: &str) {
    if !text.is_empty()
        && text
            .bytes()
            .all(|byte| byte.is_ascii_graphic() && !matches!(byte, b':' | b'"' | b'\\' | b'|'))
    {
        out.push_str(text);
    } else {
        write!(out, "{text:?}").unwrap();
    }
}

/// Emit the frame shape before the bulk tables and debug payload. The
/// exhaustive pattern makes every new bytecode field an explicit JS decision.
fn write_function_metadata(
    output: &mut String,
    code: &BytecodeFunction,
    indent: &str,
    depth: usize,
) -> Result<(), EmitError> {
    macro_rules! fields {
        ($($field:ident),+ $(,)?) => {
            let BytecodeFunction { instructions: _, $($field),+ } = code;
            $(
                let value = serde_json::to_value($field)?;
                write!(output, "{indent}{}: ", stringify!($field)).unwrap();
                write_value(output, &value, depth)?;
                output.push_str(",\n");
            )+
        };
    }
    fields!(
        name,
        source_file,
        arity,
        registers,
        captures,
        constants,
        lambda_list,
        notinline,
        vop_calls,
        handlers,
        restarts,
        keywords,
        jump_tables,
        facts,
        debug,
    );
    Ok(())
}

/// A reader-facing name for a constant operand: `COMMON-LISP::FORMAT`, `#:G1`.
pub(super) fn constant_label(
    code: &BytecodeFunction,
    nodes: &[LiteralNode],
    index: usize,
) -> Option<String> {
    let node = code
        .constants
        .get(index)
        .and_then(|constant| nodes.get(*constant as usize))?;
    let mut label = String::new();
    match node {
        LiteralNode::InternedSymbol { package, name } => {
            write_symbol_component(&mut label, package);
            label.push_str("::");
            write_symbol_component(&mut label, name);
        }
        LiteralNode::UninternedSymbol(name) => {
            label.push_str("#:");
            write_symbol_component(&mut label, name);
        }
        LiteralNode::Nil => label.push_str("COMMON-LISP::NIL"),
        LiteralNode::True => label.push_str("COMMON-LISP::T"),
        _ => return None,
    }
    Some(truncate_comment(label))
}

/// Identify the Lisp binding an operation uses or the register it calls through.
pub(super) fn instruction_label(
    instruction: &Instruction,
    code: &BytecodeFunction,
    nodes: &[LiteralNode],
) -> Option<String> {
    match instruction {
        Instruction::Call {
            callee: Callee::Value(register),
            ..
        }
        | Instruction::CallValues {
            callee: register, ..
        } => Some(format!("callee register {register}")),
        Instruction::Call {
            callee: Callee::Named(index),
            ..
        }
        | Instruction::ReadCell { symbol: index, .. }
        | Instruction::WriteCell { symbol: index, .. }
        | Instruction::DefineFunction { symbol: index, .. }
        | Instruction::ProclaimSpecial { symbol: index, .. }
        | Instruction::ProclaimInline { symbol: index, .. }
        | Instruction::SetVariableDocumentation { symbol: index, .. }
        | Instruction::WhenBound { symbol: index, .. }
        | Instruction::BindSpecial { symbol: index, .. }
        | Instruction::TryFixnumArithmetic { symbol: index, .. } => {
            constant_label(code, nodes, *index)
        }
        _ => None,
    }
}

/// Keep a trailing comment short enough to stay on one readable line.
///
/// A truncated name always ends in `...`, so the comment can never end in a
/// backslash that would continue the line.
pub(super) fn truncate_comment(label: String) -> String {
    const LIMIT: usize = 64;
    if label.chars().count() <= LIMIT {
        return label;
    }
    let cut = label
        .char_indices()
        .nth(LIMIT)
        .map_or(label.len(), |(byte, _)| byte);
    let mut truncated = label;
    truncated.truncate(cut);
    truncated.push_str("...");
    truncated
}

/// A comment naming the registers that debug information ties to one Lisp
/// variable, so a reader can follow `r[3]` in the generated step.
fn register_comment(names: &[Option<&str>]) -> String {
    const PREFIX: &str = "registers: ";
    let mut comment = String::new();
    for (register, name) in names.iter().enumerate() {
        if let Some(name) = name {
            let mut escaped = String::new();
            write_symbol_component(&mut escaped, name);
            writeln!(
                comment,
                "  // {PREFIX}r[{register}] = {}",
                truncate_comment(escaped)
            )
            .unwrap();
        }
    }
    comment
}

/// The Lisp variable names that debug information places in each register.
///
/// A register can hold different variables over disjoint live ranges. A name is
/// kept only when one variable covers the whole function, so the generated
/// comment never claims a binding that does not hold at every instruction.
fn register_variable_names<'a>(
    code: &BytecodeFunction,
    nodes: &'a [LiteralNode],
) -> Vec<Option<&'a str>> {
    let function_length = 0..code.instructions.len();
    let mut names = vec![None; code.registers];
    let mut claimed = vec![false; code.registers];
    for variable in &code.debug.variables {
        let DebugVariableLocation::Register { index, boxed } = variable.location else {
            continue;
        };
        let Some(slot) = names.get_mut(index) else {
            continue;
        };
        if std::mem::replace(&mut claimed[index], true) || boxed || variable.live != function_length
        {
            *slot = None;
            continue;
        }
        *slot =
            code.constants
                .get(variable.name as usize)
                .and_then(|constant| nodes.get(*constant as usize))
                .and_then(|node| match node {
                    LiteralNode::InternedSymbol { name, .. }
                    | LiteralNode::UninternedSymbol(name) => Some(name.as_str()),
                    _ => None,
                });
    }
    names
}

/// A lowered instruction. Statements carry one entry per source line so that a
/// multi-line instruction can never inherit another statement's indentation.
enum InlineOperation {
    Statements {
        lines: Vec<String>,
        /// The Lisp object the instruction refers to, when one names it.
        comment: Option<String>,
    },
    Branch {
        target: usize,
        condition: Option<(usize, BranchCondition)>,
    },
}

impl InlineOperation {
    fn emit(&self, steps: &mut String, next: usize) {
        match self {
            Self::Statements { lines, comment } => {
                for (index, line) in lines.iter().enumerate() {
                    write!(steps, "      {line}").unwrap();
                    // The comment names the instruction, so it follows its last line.
                    if index + 1 == lines.len() {
                        if let Some(comment) = comment {
                            write!(steps, " // {comment}").unwrap();
                        }
                    }
                    steps.push('\n');
                }
            }
            Self::Branch { target, condition } if *target != next => {
                if let Some((register, condition)) = condition {
                    let operand = if matches!(condition, BranchCondition::OutsideFixnum(..)) {
                        writeln!(steps, "      const n = r[{register}];").unwrap();
                        "n".to_owned()
                    } else {
                        format!("r[{register}]")
                    };
                    let test = condition.expression(&operand, true);
                    writeln!(steps, "      if ({test}) {{\n        frame.pc = {target};\n        continue dispatch;\n      }}").unwrap();
                } else {
                    writeln!(
                        steps,
                        "      frame.pc = {target};\n      continue dispatch;"
                    )
                    .unwrap();
                }
            }
            Self::Branch { .. } => {}
        }
    }
}

// Register, branch and value operations lower directly to JavaScript. Calls
// and control effects continue to use the shared runtime.
fn inline_operation(
    instruction: &Instruction,
    objects: &mut BTreeSet<&'static str>,
    constant_label: &dyn Fn(usize) -> Option<String>,
) -> Option<InlineOperation> {
    use Instruction::*;
    let mut object = |object| {
        objects.insert(object);
        object
    };
    let branch = |target, condition| Some(InlineOperation::Branch { target, condition });
    let lines = match instruction {
        Load(out, Immediate::Nil) => vec![format!("r[{out}] = {};", object("NIL"))],
        Load(out, Immediate::True) => vec![format!("r[{out}] = {};", object("T"))],
        Load(out, Immediate::Fixnum(value)) => vec![format!("r[{out}] = {value};")],
        Load(out, Immediate::Character(value)) => vec![format!(
            "r[{out}] = new {}({});",
            object("LispCharacter"),
            *value as u32
        )],
        Constant(out, index) => vec![format!("r[{out}] = frame.constants[{index}];")],
        Copy(out, src) => vec![format!("r[{out}] = r[{src}];")],
        Clear(range) => vec![format!(
            "r.fill({}, {}, {});",
            object("NIL"),
            range.start,
            range.end
        )],
        Jump(target) => return branch(*target, None),
        Unless(..) | IfPresent(..) | UnlessFixnum(..) | UnlessFixnumInRange(..) => {
            let (register, target, condition) = BranchCondition::for_instruction(instruction);
            if let Some(name) = condition.runtime_object() {
                object(name);
            }
            return branch(target, Some((register, condition)));
        }
        SetValues(range) if range.len() < MULTIPLE_VALUES_LIMIT => {
            vec![format!(
                "task.values = r.slice({}, {});",
                range.start, range.end
            )]
        }
        BindValues(range) => {
            let (start, end) = (range.start, range.end);
            let nil = object("NIL");
            vec![
                format!("for (let i = {start}; i < {end}; i++) {{"),
                format!("  r[i] = task.values[i - {start}] ?? {nil};"),
                "}".into(),
                "task.values = [];".into(),
            ]
        }
        ReadValue(out, index) => vec![format!(
            "r[{out}] = task.values[{index}] ?? {};",
            object("NIL")
        )],
        Capture(out, index) => vec![format!("r[{out}] = frame.captures[{index}];")],
        OptionalArgument(index, out) => vec![format!(
            "r[{out}] = frame.arguments[{index}] ?? {};",
            object("UNBOUND")
        )],
        ReleaseArguments => vec![
            "frame.arguments = [];".into(),
            "frame.keywords = [];".into(),
        ],
        _ => return None,
    };
    let comment = match instruction {
        Constant(_, index) => constant_label(*index),
        _ => None,
    };
    Some(InlineOperation::Statements { lines, comment })
}

/// A canonical conditional jump shared by both generated entry points.
pub(super) enum BranchCondition {
    Nil,
    Present,
    OutsideFixnum(i64, i64),
}

impl BranchCondition {
    pub(super) fn for_instruction(instruction: &Instruction) -> (usize, usize, Self) {
        match *instruction {
            Instruction::Unless(register, target) => (register, target, Self::Nil),
            Instruction::IfPresent(register, target) => (register, target, Self::Present),
            Instruction::UnlessFixnum(register, target) => {
                let (low, high) = CompilationTarget::javascript().fixnum_bounds();
                (register, target, Self::OutsideFixnum(low, high))
            }
            Instruction::UnlessFixnumInRange(register, low, high, target) => (
                register,
                target,
                Self::OutsideFixnum(i64::from(low), i64::from(high)),
            ),
            _ => unreachable!("conditional branch"),
        }
    }

    pub(super) fn runtime_object(&self) -> Option<&'static str> {
        match self {
            Self::Nil => Some("NIL"),
            Self::Present => Some("UNBOUND"),
            Self::OutsideFixnum(..) => None,
        }
    }

    pub(super) fn expression(&self, operand: &str, taken: bool) -> String {
        match (self, taken) {
            (Self::Nil, true) => format!("{operand} === NIL"),
            (Self::Nil, false) => format!("{operand} !== NIL"),
            (Self::Present, true) => format!("{operand} !== UNBOUND"),
            (Self::Present, false) => format!("{operand} === UNBOUND"),
            (Self::OutsideFixnum(low, high), true) => format!(
                "typeof {operand} !== 'number' || !Number.isInteger({operand}) || {operand} < {low} || {operand} > {high}"
            ),
            (Self::OutsideFixnum(low, high), false) => format!(
                "typeof {operand} === 'number' && Number.isInteger({operand}) && {operand} >= {low} && {operand} <= {high}"
            ),
        }
    }
}

fn operation(instruction: &Instruction) -> Result<(String, Value), EmitError> {
    match serde_json::to_value(instruction)? {
        Value::String(name) => Ok((name, Value::Null)),
        Value::Object(map) => {
            let (name, mut payload) = map.into_iter().next().expect("instruction variant");
            if instruction.source_offset().is_some() {
                // Source offsets are already recorded at the instruction PC.
                payload
                    .as_object_mut()
                    .expect("source-bearing operands")
                    .remove("at");
            }
            Ok((name, payload))
        }
        _ => unreachable!("instruction serialization"),
    }
}

fn literal(node: &LiteralNode) -> Result<Value, EmitError> {
    let mut value = serde_json::to_value(node)?;
    match node {
        LiteralNode::Fixnum(_) => decimal(&mut value["Fixnum"]),
        LiteralNode::DoubleFloat(_) => decimal(&mut value["DoubleFloat"]),
        LiteralNode::RandomState(_) => decimals(&mut value["RandomState"]),
        LiteralNode::HashTable { .. } => {
            decimal(&mut value["HashTable"]["rehash_size"]);
            decimal(&mut value["HashTable"]["rehash_threshold"]);
        }
        LiteralNode::Array {
            contents: zkcl_bytecode::ArrayContents::DoubleFloats(_),
            ..
        } => {
            decimals(&mut value["Array"]["contents"]["DoubleFloats"]);
        }
        LiteralNode::SimdMask(_) => decimal(&mut value["SimdMask"]["bits"]),
        _ => {}
    }
    Ok(value)
}

fn decimal(value: &mut Value) {
    *value = Value::String(value.to_string());
}

fn decimals(value: &mut Value) {
    for item in value.as_array_mut().expect("64-bit payload array") {
        decimal(item);
    }
}
